export const DICTIONARIES: Record<string, Dict> = { vi, en };

/** Payload's language codes we ship copy for; anything else falls back to `vi`. */
export const DEFAULT_LANGUAGE = "vi";

/**
 * Resolve a key for a language, filling `{placeholders}` from `vars`. Unknown languages fall back
 * to Vietnamese rather than printing the raw key.
 */
export function translate(
  language: string | undefined,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const dict = DICTIONARIES[language || ""] || DICTIONARIES[DEFAULT_LANGUAGE]!;
  let out = dict[key] ?? DICTIONARIES[DEFAULT_LANGUAGE]![key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.split(`{${name}}`).join(String(value));
    }
  }
  return out;
}

export type Translator = (key: TranslationKey, vars?: Record<string, string | number>) => string;

/** Bind a translator to one language — for server components. */
export const translator =
  (language: string | undefined): Translator =>
  (key, vars) =>
    translate(language, key, vars);
